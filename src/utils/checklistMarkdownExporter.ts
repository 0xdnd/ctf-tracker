import { Machine } from '../types';
import { MethodologyPhase, ChecklistItemStatus } from '../types/checklist';
import { generateApplicablePhases } from '../data/methodologyFramework';

export function exportChecklistToMarkdown(machine: Machine): string {
  const openPorts = machine.openPorts || [];
  const checklist = machine.checklist;
  const itemsState = checklist?.itemsState || {};
  const applicablePhases = generateApplicablePhases(machine, openPorts);

  // Compute total statistics
  let totalApplicableItems = 0;
  let completedItems = 0;
  let inProgressItems = 0;
  let naItems = 0;

  applicablePhases.forEach((phase) => {
    phase.subcategories.forEach((subcat) => {
      subcat.items.forEach((item) => {
        const state = itemsState[item.id]?.status || 'todo';
        if (state === 'done') completedItems++;
        else if (state === 'in_progress') inProgressItems++;
        else if (state === 'na') naItems++;
        totalApplicableItems++;
      });
    });
  });

  const activeDenom = totalApplicableItems - naItems;
  const percentComplete = activeDenom > 0 ? Math.round((completedItems / activeDenom) * 100) : 0;
  const today = new Date().toISOString().slice(0, 10);

  let md = `---
title: "Attack Checklist: ${machine.name}"
target_ip: "${machine.ip}"
platform: "${machine.platform}"
os: "${machine.os}"
difficulty: "${machine.difficulty}"
completion: "${percentComplete}% (${completedItems}/${activeDenom} tasks completed)"
open_ports: [${openPorts.join(', ')}]
date_exported: "${today}"
---

# ⚔️ Attack Lifecycle Checklist: ${machine.name}
**Target IP:** \`${machine.ip}\` | **OS:** ${machine.os} | **Platform:** ${machine.platform}
**Methodology Progress:** \`${percentComplete}%\` (${completedItems} Completed, ${inProgressItems} In Progress, ${naItems} N/A)
**Detected Ports:** ${openPorts.length > 0 ? openPorts.map(p => `\`${p}\``).join(' ') : '_None recorded_'}

---
`;

  applicablePhases.forEach((phase) => {
    // Phase header
    let phaseTotal = 0;
    let phaseDone = 0;
    phase.subcategories.forEach((sub) => {
      sub.items.forEach((it) => {
        const st = itemsState[it.id]?.status || 'todo';
        if (st !== 'na') phaseTotal++;
        if (st === 'done') phaseDone++;
      });
    });

    const phasePct = phaseTotal > 0 ? Math.round((phaseDone / phaseTotal) * 100) : 0;

    md += `\n## ${phase.title} — \`${phasePct}%\`\n`;
    md += `_${phase.description}_\n\n`;

    phase.subcategories.forEach((subcat) => {
      md += `### ${subcat.title}\n`;
      subcat.items.forEach((item) => {
        const itemRecord = itemsState[item.id];
        const status: ChecklistItemStatus = itemRecord?.status || 'todo';

        let box = '[ ]';
        let prefix = '';
        let suffix = '';

        if (status === 'done') {
          box = '[x]';
        } else if (status === 'in_progress') {
          box = '[-]';
          prefix = '**[IN PROGRESS]** ';
        } else if (status === 'na') {
          box = '[x]';
          prefix = '~~';
          suffix = '~~ _(N/A)_';
        }

        md += `- ${box} ${prefix}${item.title}${suffix}\n`;

        if (item.commandSnippet) {
          md += `  \`\`\`bash\n  ${item.commandSnippet}\n  \`\`\`\n`;
        }

        if (itemRecord?.notes) {
          md += `  > 📝 **Field Note:** ${itemRecord.notes.replace(/\n/g, '\n  > ')}\n`;
        }
      });
      md += `\n`;
    });
  });

  md += `\n---\n*Generated by ZeroBox // Attack Lifecycle Engine*\n`;
  return md;
}
