export const SECTION_GUIDES: Record<string, SectionGuide> = Object.fromEntries(
  Object.values(GUIDE_META).map((meta) => [meta.id, { ...meta, steps: GUIDE_STEPS[meta.id] ?? [] }]),
);

/** The steps a guide runs. */
export function guideSteps(id: string): TourStep[] {
  return GUIDE_STEPS[id] ?? [];
}

/** The step with its stand-in copy, for when its alternative anchor is the one on the page. */
export function withStandInCopy(step: TourStep): TourStep {
  return { ...step, title: step.altTitle ?? step.title, body: step.altBody ?? step.body };
}

/**
 * A step as it runs at this screen size. Every read of a step's anchor or copy goes through here. The two
 * sizes keep the same number of steps, so turning a phone mid-guide cannot lose your place.
 */
export function resolveStep(step: TourStep, isPhone: boolean): TourStep {
  if (!isPhone) return step;
  return {
    ...step,
    anchor: step.phoneCentered ? undefined : (step.phoneAnchor ?? step.anchor),
    altAnchor: step.phoneCentered ? undefined : step.altAnchor,
    title: step.phoneTitle ?? step.title,
    body: step.phoneBody ?? step.body,
  };
}
