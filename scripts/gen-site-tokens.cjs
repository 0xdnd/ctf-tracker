#!/usr/bin/env node
/**
 * Generates scripts/site/css/00-tokens.generated.css from the app's default dark theme
 * (the `.dark, [data-theme="obsidian"].dark ...` block in src/index.css), so the public site and the
 * app share one source for surfaces, borders, text, accent and radii. Site-only tokens (band, hover
 * buttons, spacing, type scale, motion) stay in 00-tokens.css. Run in `npm run build` before prerender.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src', 'index.css');
const OUT = path.join(ROOT, 'scripts', 'site', 'css', '00-tokens.generated.css');

// site variable -> app variable (RGB triplet) or app radius (length)
const MAP = [
  ['--bg', '--surface-base'],
  ['--card', '--surface-card'],
  ['--elev', '--surface-elevated'],
  ['--code', '--surface-sunken'],
  ['--hover', '--surface-hover'],
  ['--line', '--border-subtle'],
  ['--line-strong', '--border-strong'],
  ['--text', '--text-primary'],
  ['--text-2', '--text-secondary'],
  ['--muted', '--text-muted'],
  ['--faint', '--text-tertiary'],
  ['--accent', '--border-accent'],
  ['--accent-ink', '--accent-fg'],
  ['--ok', '--cyber-emerald'],
  ['--r-md', '--radius-md'],
  ['--r-lg', '--radius-lg'],
];

const css = fs.readFileSync(SRC, 'utf8');
const start = css.search(/^\.dark,\s*\n\[data-theme="obsidian"\]\.dark/m);
if (start < 0) throw new Error('gen-site-tokens: obsidian dark block not found in src/index.css');
const block = css.slice(start, css.indexOf('\n}', start));

function read(name) {
  const m = block.match(new RegExp('^\\s*' + name.replace(/-/g, '\\-') + ':\\s*([^;]+);', 'm'));
  if (!m) throw new Error('gen-site-tokens: ' + name + ' missing in the obsidian dark block');
  return m[1].trim();
}
const hex = (triplet) => {
  const p = triplet.split(/\s+/).map(Number);
  if (p.length !== 3 || p.some((n) => !Number.isInteger(n) || n < 0 || n > 255)) throw new Error('gen-site-tokens: bad triplet ' + triplet);
  return '#' + p.map((n) => n.toString(16).padStart(2, '0')).join('');
};

const decls = MAP.map(([site, app]) => {
  const v = read(app);
  return site + ':' + (/^\d/.test(v) && !/px$/.test(v) ? hex(v) : v) + ';';
});
const lines = decls.slice();
// Header-bg is the page background at .82 alpha.
const bg = read('--surface-base').split(/\s+/).join(' ');
lines.push('--header-bg:rgb(' + bg + '/.82);');

const out = '/* GENERATED by scripts/gen-site-tokens.cjs from src/index.css (obsidian dark). Do not edit. */\n:root{\n' + lines.join('\n') + '\n}\n';
fs.writeFileSync(OUT, out);
console.log('gen-site-tokens: wrote ' + path.relative(ROOT, OUT) + ' (' + MAP.length + ' tokens)');
