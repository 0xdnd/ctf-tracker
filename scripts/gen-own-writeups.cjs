// Own-writeup manifest: node scripts/gen-own-writeups.cjs [--check]
// Writes src/data/ownWriteups.ts ({ machineId: page slug }) for machines with an on-site writeup; --check only compares and exits 1 if stale.
const fs = require('fs');
const path = require('path');
const { getModel, getWriteups } = require('./lib/content-model.cjs');

const outFile = path.resolve(__dirname, '..', 'src', 'data', 'ownWriteups.ts');
const rel = 'src/data/ownWriteups.ts';

function render() {
  getWriteups();
  const entries = getModel()
    .machines.filter((m) => m.hasSiteWriteup)
    .map((m) => [m.id, m.slug])
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const body = entries.map(([id, slug]) => `  ${JSON.stringify(id)}: ${JSON.stringify(slug)},`).join('\n');
  return `// Generated by scripts/gen-own-writeups.cjs (npm run writeups:manifest); do not edit by hand.
// Maps machine id to the page slug of its on-site writeup (/machines/<slug>/#writeup).
export const OWN_WRITEUPS: Readonly<Record<string, string>> = {${body ? `\n${body}\n` : ''}};
`;
}

/** Returns { ok, message } without writing anything. */
function checkManifest() {
  const next = render();
  if (!fs.existsSync(outFile)) return { ok: false, message: `${rel} is missing; run npm run writeups:manifest` };
  const cur = fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n');
  if (cur !== next) return { ok: false, message: `${rel} is out of date; run npm run writeups:manifest` };
  return { ok: true, message: `${rel} is up to date` };
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const r = checkManifest();
    console.log(r.ok ? `OK   ${r.message}` : `FAIL ${r.message}`);
    process.exit(r.ok ? 0 : 1);
  }
  const next = render();
  fs.writeFileSync(outFile, next);
  console.log(`wrote ${rel} (${(next.match(/^ {2}"/gm) || []).length} entries)`);
}

module.exports = { checkManifest };
